"""Window that lists and manages the players."""

from typing import TYPE_CHECKING, Callable, List, Optional

from PySide6.QtGui import QCloseEvent
from PySide6.QtWidgets import QDialog, QHeaderView, QTableWidgetItem

from ttea.controller import PlayerListController
from ttea.ui import Ui_PlayerListView  # class generated by pyside6-uic
from ttea.util import MessageService, QtDateFormat
from ttea.window import WindowConfig

# Type-checking-only imports, to avoid circular imports at run time
if TYPE_CHECKING:
    from ttea.model import Player
    from ttea.view import PlayerEditView


class PlayerListView(QDialog, Ui_PlayerListView, WindowConfig):
    """Dialog that lists and manages the players.

    Shows a searchable table (ID and name) and a details panel. The
    widgets come from ``Ui_PlayerListView``; all actions are handled by
    ``PlayerListController``, which calls the methods below to update
    the window.

    Parameters
    ----------
    parent : QDialog | None, optional
        Parent widget. Default is None.
    player_edit_view_factory : Callable | None, optional
        Creates the edit dialog: ``factory(parent, player)`` returns the
        edit view. Default is None.

    Attributes
    ----------
    msg : MessageService
        Service used to show dialogs.
    controller : PlayerListController
        Controller of the window.

    Methods
    -------
    populate_table(players)
        Fill the table.
    clear_details()
        Clear the details panel.
    display_details(player)
        Show the details of a player.
    get_selected_id()
        Return the ID of the selected row.
    select_row_by_id(player_id)
        Select the row of an ID.

    Notes
    -----
    The window is fixed at 10% narrower and 5% shorter than the parent.
    Closing it asks for confirmation (translated with ``self.tr()``).
    """

    def __init__(
        self,
        parent: Optional[QDialog] = None,
        player_edit_view_factory: Optional[
            Callable[[Optional[QDialog], Optional["Player"]], "PlayerEditView"]
        ] = None,
    ) -> None:
        super().__init__(parent)

        self.setupUi(self)
        self.msg = MessageService(self)

        self.setup_window(
            self.windowTitle(),
            self.windowIcon(),
            WindowConfig.DECREMENT_SIZE_PERCENT,
            10,
            5,
            parent,
        )

        self.controller = PlayerListController(self, player_edit_view_factory)

        # Column widths: ID fits its content, name stretches
        self.tbl_player.horizontalHeader().setSectionResizeMode(
            0, QHeaderView.ResizeToContents
        )
        self.tbl_player.horizontalHeader().setSectionResizeMode(
            1, QHeaderView.Stretch
        )

    # Methods called by the controller (keeps the view decoupled)

    def populate_table(self, players: List["Player"]) -> None:
        """Fill the table with ID and name of each player.

        Parameters
        ----------
        players : list[Player]
            The players to show.

        Notes
        -----
        Table signals are blocked while filling, so no selection change
        is reported.
        """
        self.tbl_player.blockSignals(True)
        self.tbl_player.setRowCount(0)

        for player in players:
            row = self.tbl_player.rowCount()
            self.tbl_player.insertRow(row)
            self.tbl_player.setItem(row, 0, QTableWidgetItem(str(player.id)))
            self.tbl_player.setItem(row, 1, QTableWidgetItem(player.name))

        self.tbl_player.blockSignals(False)

    def clear_details(self) -> None:
        """Clear all fields of the details panel."""
        self.lbl_id_value.setText("")
        self.lbl_name_value.setText("")
        self.lbl_birth_date_value.setText("")
        self.lbl_observation_value.setText("")

    def display_details(self, player: Optional["Player"]) -> None:
        """Show the details of a player.

        Parameters
        ----------
        player : Player | None
            The player; None clears the panel.

        Notes
        -----
        The birth date is formatted with
        ``QtDateFormat.format_python_date`` and an empty observation
        shows a dash.
        """
        if not player:
            self.clear_details()
            return

        self.lbl_id_value.setText(str(player.id))
        self.lbl_name_value.setText(player.name)
        self.lbl_birth_date_value.setText(
            QtDateFormat.format_python_date(player.birth_date)
        )
        self.lbl_observation_value.setWordWrap(True)
        self.lbl_observation_value.setMaximumWidth(
            int(self.size().width()) / 2
        )
        self.lbl_observation_value.setText(player.observation or "—")

    def get_selected_id(self) -> Optional[int]:
        """Return the ID of the selected player.

        Returns
        -------
        int | None
            ID read from the first column, or None when nothing is
            selected or the text is not a number.
        """
        items = self.tbl_player.selectedItems()
        if not items:
            return None
        try:
            return int(items[0].text())
        except (ValueError, AttributeError):
            return None

    def select_row_by_id(self, player_id: int) -> None:
        """Select the row of a player ID and show it.

        Parameters
        ----------
        player_id : int
            ID to select; values of 0 or less are ignored.

        Notes
        -----
        Signals are blocked while selecting, and
        ``controller.on_table_selection`` is called afterwards.
        """
        if player_id <= 0:
            return

        self.tbl_player.blockSignals(True)
        for row in range(self.tbl_player.rowCount()):
            item = self.tbl_player.item(row, 0)
            if item and int(item.text()) == player_id:
                self.tbl_player.selectRow(row)
                self.tbl_player.scrollToItem(item)
                break
        self.tbl_player.blockSignals(False)
        self.controller.on_table_selection()

    def closeEvent(self, event: QCloseEvent) -> None:
        """Ask for confirmation before closing the window.

        Parameters
        ----------
        event : QCloseEvent
            Close event; accepted only if the user confirms.
        """
        if self.msg.question(self.tr("Deseja sair do cadastro?"), None, True):
            event.accept()
        else:
            event.ignore()
