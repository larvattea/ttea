"""Window that lists and manages the institution facilities."""

from typing import TYPE_CHECKING, Callable, List, Optional

from PySide6.QtGui import QCloseEvent
from PySide6.QtWidgets import QDialog, QHeaderView, QTableWidgetItem

from ttea.controller import InstitutionFacilityListController
from ttea.ui import \
    Ui_InstitutionFacilityListView  # class generated by pyside6-uic
from ttea.util import MessageService
from ttea.window import WindowConfig

# Type-checking-only imports, to avoid circular imports at run time
if TYPE_CHECKING:
    from ttea.model import InstitutionFacility
    from ttea.view import InstitutionFacilityEditView


class InstitutionFacilityListView(
    QDialog, Ui_InstitutionFacilityListView, WindowConfig
):
    """Dialog that lists and manages the institution facilities.

    Shows a searchable table (ID and name) and a details panel. The
    widgets come from ``Ui_InstitutionFacilityListView``; all actions
    are handled by ``InstitutionFacilityListController``, which calls
    the methods below to update the window.

    Parameters
    ----------
    parent : QDialog | None, optional
        Parent widget. Default is None.
    institutionfacility_edit_view_factory : Callable | None, optional
        Creates the edit dialog: ``factory(parent,
        institutionfacility)`` returns the edit view. Default is None.

    Attributes
    ----------
    msg : MessageService
        Service used to show dialogs.
    controller : InstitutionFacilityListController
        Controller of the window.

    Methods
    -------
    populate_table(institutionfacilities)
        Fill the table.
    clear_details()
        Clear the details panel.
    display_details(institutionfacility)
        Show the details of an institution facility.
    get_selected_id()
        Return the ID of the selected row.
    select_row_by_id(institutionfacility_id)
        Select the row of an ID.

    Notes
    -----
    The window is fixed at 10% narrower and 5% shorter than the parent.
    Closing it asks for confirmation (translated with ``self.tr()``).
    """

    def __init__(
        self,
        parent: Optional[QDialog] = None,
        institutionfacility_edit_view_factory: Optional[
            Callable[
                [Optional[QDialog], Optional["InstitutionFacility"]],
                "InstitutionFacilityEditView",
            ]
        ] = None,
    ) -> None:
        super().__init__(parent)
        self.setupUi(self)
        self.msg = MessageService(self)

        self.setup_window(
            self.windowTitle(),
            self.windowIcon(),
            WindowConfig.DECREMENT_SIZE_PERCENT,
            10,
            5,
            parent,
        )

        self.controller = InstitutionFacilityListController(
            self, institutionfacility_edit_view_factory
        )

        # Column widths: ID fits its content, name stretches
        self.tbl_institution.horizontalHeader().setSectionResizeMode(
            0, QHeaderView.ResizeToContents
        )
        self.tbl_institution.horizontalHeader().setSectionResizeMode(
            1, QHeaderView.Stretch
        )

    # Methods called by the controller (keeps the view decoupled)
    def populate_table(
        self, institutionfacilities: List["InstitutionFacility"]
    ) -> None:
        """Fill the table with ID and name of each institution facility.

        Parameters
        ----------
        institutionfacilities : list[InstitutionFacility]
            The institution facilities to show.

        Notes
        -----
        Table signals are blocked while filling, so no selection change
        is reported.
        """
        self.tbl_institution.blockSignals(True)
        self.tbl_institution.setRowCount(0)

        for institutionfacility in institutionfacilities:
            row = self.tbl_institution.rowCount()
            self.tbl_institution.insertRow(row)
            self.tbl_institution.setItem(
                row, 0, QTableWidgetItem(str(institutionfacility.id))
            )
            self.tbl_institution.setItem(
                row, 1, QTableWidgetItem(institutionfacility.name)
            )

        self.tbl_institution.blockSignals(False)

    def clear_details(self) -> None:
        """Clear all fields of the details panel."""
        self.lbl_id_value.setText("")
        self.lbl_name_value.setText("")
        self.lbl_type_value.setText("")
        self.lbl_address_value.setText("")

    def display_details(
        self, institutionfacility: Optional["InstitutionFacility"]
    ) -> None:
        """Show the details of an institution facility.

        Parameters
        ----------
        institutionfacility : InstitutionFacility | None
            The institution facility; None clears the panel.

        Notes
        -----
        The type is shown with its translated name, and an empty address
        shows a dash.
        """
        if not institutionfacility:
            self.clear_details()
            return

        self.lbl_id_value.setText(str(institutionfacility.id))
        self.lbl_name_value.setText(institutionfacility.name)
        self.lbl_type_value.setText(
            str(
                self.controller.get_institutionfacility_types()[
                    institutionfacility.type
                ]
            )
        )
        self.lbl_address_value.setText(institutionfacility.address or "—")

    def get_selected_id(self) -> Optional[int]:
        """Return the ID of the selected institution facility.

        Returns
        -------
        int | None
            ID read from the first column, or None when nothing is
            selected or the text is not a number.
        """
        items = self.tbl_institution.selectedItems()
        if not items:
            return None
        try:
            return int(items[0].text())
        except (ValueError, AttributeError):
            return None

    def select_row_by_id(self, institutionfacility_id: int) -> None:
        """Select the row of an institution facility ID and show it.

        Parameters
        ----------
        institutionfacility_id : int
            ID to select; values of 0 or less are ignored.

        Notes
        -----
        Signals are blocked while selecting, and
        ``controller.on_table_selection`` is called afterwards.
        """
        if institutionfacility_id <= 0:
            return

        self.tbl_institution.blockSignals(True)
        for row in range(self.tbl_institution.rowCount()):
            item = self.tbl_institution.item(row, 0)
            if item and int(item.text()) == institutionfacility_id:
                self.tbl_institution.selectRow(row)
                self.tbl_institution.scrollToItem(item)
                break
        self.tbl_institution.blockSignals(False)
        self.controller.on_table_selection()

    def closeEvent(self, event: QCloseEvent) -> None:
        """Ask for confirmation before closing the window.

        Parameters
        ----------
        event : QCloseEvent
            Close event; accepted only if the user confirms.
        """
        if self.msg.question(self.tr("Deseja sair do cadastro?"), None, True):
            event.accept()
        else:
            event.ignore()
