"""Views (Qt windows and dialogs) of the T-TEA platform.

Developed by the Larva UDESC team.

This package provides the windows and dialogs of the platform. Each view
builds its widgets from the ``ttea.ui`` classes generated by pyside6-uic
and delegates its logic to a controller.

Attributes
----------
__version__ : str
    The current version of the package.
__date__ : str
    The release date of this version.
__author__ : str
    The development team.
__license__ : str
    The license under which the package is distributed.

See Also
--------
AboutView
    Information about the project.
AutomaticCalibrationView
    Automatic calibration with a ChArUco board.
CalibrationSettingView
    Calibration settings.
CalibrationView
    Hardware data and calibration modes.
InstitutionFacilityEditView
    Create or edit an institution/facility.
InstitutionFacilityListView
    List of institutions/facilities.
LanguageView
    Language selection.
MainView
    Main window.
ManualCalibrationView
    Manual calibration.
PlayerEditView
    Create or edit a player.
PlayerGameLaunchView
    Game launch (game session).
PlayerListView
    List of players.
ProfessionalEditView
    Create or edit a professional.
ProfessionalListView
    List of professionals.
SplashScreen
    Splash screen shown during startup.

Notes
-----
``HelpView`` is not exported here, so Qt WebEngine is loaded only when
the help is opened.

This package is maintained by the Larva UDESC team and is under active
development. Contributions and bug reports are welcome at:
https://github.com/larvattea/ttea
"""

