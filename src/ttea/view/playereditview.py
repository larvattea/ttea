"""Dialog to create or edit a player."""

from typing import TYPE_CHECKING, Optional

from PySide6.QtWidgets import QDialog

from ttea.controller import PlayerEditController
from ttea.ui import Ui_PlayerEditView  # class generated by pyside6-uic
from ttea.window import WindowConfig

# Type-checking-only imports, to avoid circular imports at run time
if TYPE_CHECKING:
    from ttea.model import Player


class PlayerEditView(QDialog, Ui_PlayerEditView, WindowConfig):
    """Modal dialog for creating or editing a player.

    The widgets come from ``Ui_PlayerEditView`` (Qt Designer); field
    filling, validation and data extraction are done by
    ``PlayerEditController``.

    Parameters
    ----------
    parent : QWidget | None, optional
        Parent widget, usually the list window. Default is None.
    player : Player | None, optional
        Player to edit; None opens the dialog in creation mode. Default
        is None.

    Attributes
    ----------
    controller : PlayerEditController
        Controller of the dialog.

    Notes
    -----
    The title gets the suffix " - Novo" or " - Editar" (translated with
    ``self.tr()``), and the window is 10% narrower and shorter than the
    parent (``WindowConfig.setup_window``).
    """

    def __init__(self, parent=None, player: Optional["Player"] = None):
        super().__init__(parent)

        self.setupUi(self)

        # Window: title, icon and size relative to the parent
        action = self.tr("Novo") if not player else self.tr("Editar")

        self.setup_window(
            f"{self.windowTitle()} - {action}",
            self.windowIcon(),
            WindowConfig.DECREMENT_SIZE_PERCENT,
            10,  # percent decrease in width
            10,  # percent decrease in height
            parent,
        )

        # The controller fills the fields when editing
        self.controller = PlayerEditController(self, player)
