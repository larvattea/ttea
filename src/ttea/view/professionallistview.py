"""Window that lists and manages the professionals."""

from typing import TYPE_CHECKING, Callable, List, Optional

from PySide6.QtGui import QCloseEvent
from PySide6.QtWidgets import QDialog, QHeaderView, QTableWidgetItem

from ttea.controller import ProfessionalListController
from ttea.ui import Ui_ProfessionalListView  # class generated by pyside6-uic
from ttea.util import MessageService
from ttea.window import WindowConfig

# Type-checking-only imports, to avoid circular imports at run time
if TYPE_CHECKING:
    from ttea.model import Professional
    from ttea.view import ProfessionalEditView


class ProfessionalListView(QDialog, Ui_ProfessionalListView, WindowConfig):
    """Dialog that lists and manages the professionals.

    Shows a searchable table (ID and name) and a details panel. The
    widgets come from ``Ui_ProfessionalListView``; all actions are
    handled by ``ProfessionalListController``, which calls the methods
    below to update the window.

    Parameters
    ----------
    parent : QDialog | None, optional
        Parent widget. Default is None.
    professional_edit_view_factory : Callable | None, optional
        Creates the edit dialog: ``factory(parent, professional)``
        returns the edit view. Default is None.

    Attributes
    ----------
    msg : MessageService
        Service used to show dialogs.
    controller : ProfessionalListController
        Controller of the window.

    Methods
    -------
    populate_table(professionals)
        Fill the table.
    clear_details()
        Clear the details panel.
    display_details(professional)
        Show the details of a professional.
    get_selected_id()
        Return the ID of the selected row.
    select_row_by_id(professional_id)
        Select the row of an ID.

    Notes
    -----
    The window is fixed at 10% narrower and 5% shorter than the parent.
    Closing it asks for confirmation (translated with ``self.tr()``).
    """

    def __init__(
        self,
        parent: Optional[QDialog] = None,
        professional_edit_view_factory: Optional[
            Callable[
                [Optional[QDialog], Optional["Professional"]],
                "ProfessionalEditView",
            ]
        ] = None,
    ) -> None:

        super().__init__(parent)
        self.setupUi(self)
        self.msg = MessageService(self)

        self.setup_window(
            self.windowTitle(),
            self.windowIcon(),
            WindowConfig.DECREMENT_SIZE_PERCENT,
            10,
            5,
            parent,
        )

        self.controller = ProfessionalListController(
            self, professional_edit_view_factory
        )

        # Column widths: ID fits its content, name stretches
        self.tbl_professional.horizontalHeader().setSectionResizeMode(
            0, QHeaderView.ResizeToContents
        )
        self.tbl_professional.horizontalHeader().setSectionResizeMode(
            1, QHeaderView.Stretch
        )

    # Methods called by the controller (keeps the view decoupled)
    def populate_table(self, professionals: List["Professional"]) -> None:
        """Fill the table with ID and name of each professional.

        Parameters
        ----------
        professionals : list[Professional]
            The professionals to show.

        Notes
        -----
        Table signals are blocked while filling, so no selection change
        is reported.
        """
        self.tbl_professional.blockSignals(True)
        self.tbl_professional.setRowCount(0)

        for professional in professionals:
            row = self.tbl_professional.rowCount()
            self.tbl_professional.insertRow(row)
            self.tbl_professional.setItem(
                row, 0, QTableWidgetItem(str(professional.id))
            )
            self.tbl_professional.setItem(
                row, 1, QTableWidgetItem(professional.name)
            )

        self.tbl_professional.blockSignals(False)

    def clear_details(self) -> None:
        """Clear all fields of the details panel."""
        self.lbl_id_value.setText("")
        self.lbl_name_value.setText("")
        self.lbl_type_value.setText("")

    def display_details(self, professional: Optional["Professional"]) -> None:
        """Show the details of a professional.

        Parameters
        ----------
        professional : Professional | None
            The professional; None clears the panel.

        Notes
        -----
        The type is shown with its translated name.
        """
        if not professional:
            self.clear_details()
            return

        self.lbl_id_value.setText(str(professional.id))
        self.lbl_name_value.setText(professional.name)
        self.lbl_type_value.setText(
            str(self.controller.get_professional_types()[professional.type])
        )

    def get_selected_id(self) -> Optional[int]:
        """Return the ID of the selected professional.

        Returns
        -------
        int | None
            ID read from the first column, or None when nothing is
            selected or the text is not a number.
        """
        items = self.tbl_professional.selectedItems()
        if not items:
            return None
        try:
            return int(items[0].text())
        except (ValueError, AttributeError):
            return None

    def select_row_by_id(self, professional_id: int) -> None:
        """Select the row of a professional ID and show it.

        Parameters
        ----------
        professional_id : int
            ID to select; values of 0 or less are ignored.

        Notes
        -----
        Signals are blocked while selecting, and
        ``controller.on_table_selection`` is called afterwards.
        """
        if professional_id <= 0:
            return

        self.tbl_professional.blockSignals(True)
        for row in range(self.tbl_professional.rowCount()):
            item = self.tbl_professional.item(row, 0)
            if item and int(item.text()) == professional_id:
                self.tbl_professional.selectRow(row)
                self.tbl_professional.scrollToItem(item)
                break
        self.tbl_professional.blockSignals(False)
        self.controller.on_table_selection()

    def closeEvent(self, event: QCloseEvent) -> None:
        """Ask for confirmation before closing the window.

        Parameters
        ----------
        event : QCloseEvent
            Close event; accepted only if the user confirms.
        """
        if self.msg.question(self.tr("Deseja sair do cadastro?"), None, True):
            event.accept()
        else:
            event.ignore()
